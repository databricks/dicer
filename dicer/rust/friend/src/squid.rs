use std::cmp::Ordering;
use std::fmt::{Debug, Formatter};
use std::hash::Hash;

use tonic::Status;
use caching_rust_util::{
    saturated_system_time_to_unix_millis,
    system_time_from_unix_millis,
    Clock,
    PrettySystemTime,
};
use dicer_friend_proto_friend_proto_library::dicer::friend::SquidP;
use dicer_rust_external_types::ResourceAddress;
use uuid::Uuid;

/// Identifier for a resource incarnation to which requests will be routed,
/// consisting of a resource address, creation time, and UUID. Collectively,
/// these fields represent the Slicelet incarnation uniQUe ID (SQUID). See
/// accessor documentation to understand how these fields are used and why they
/// are important.
#[derive(Eq, PartialEq, Hash, Clone)]
pub struct Squid {
    resource_address: ResourceAddress,

    /// We use a millisecond precision representation instead of `SystemTime`
    /// because that is the precision of the proto representation, and we need
    /// to ensure that SQUIDs can round-trip.
    creation_time_millis: i64,

    resource_uuid: Uuid,
}

impl Squid {
    /// Creates a [[Squid]] with the current time from `clock` as creation time,
    /// the given address, and the given UUID. The reason that we take an
    /// externally constructed UUID rather than creating a new random one is
    /// that the UUID matches the k8s pod UUID when it is available.
    pub fn create_for_new_incarnation(
        clock: &Clock,
        resource_address: ResourceAddress,
        resource_uuid: Uuid,
    ) -> Squid {
        Squid {
            resource_address,
            creation_time_millis: saturated_system_time_to_unix_millis(clock.now()),
            resource_uuid,
        }
    }

    /// Address of the Slicelet that is used to route requests to the Slicelet.
    pub fn resource_address(&self) -> &ResourceAddress {
        &self.resource_address
    }

    /// Creation time for the SQUID in milliseconds since the Unix epoch.
    ///
    /// If the Assigner thinks that two Slicelet incarnations with the same
    /// resource address are healthy at the same time (both have recent
    /// heartbeats), the resource incarnation with the more recent creation time
    /// will be preferred in the generated assignment. Note that an artificially
    /// advanced creation time (e.g., due to clock skew) will cause trouble but
    /// only transiently: after the offending Slicelet stops, it will take a few
    /// tens of seconds for the Assigner to decide it's dead and to exclude it
    /// from the assignment.
    pub fn creation_time_millis(&self) -> i64 {
        self.creation_time_millis
    }

    /// Globally unique ID for the incarnation of the Slicelet. This is
    /// typically the UUID generated by k8s to identify an "occurrence" of a
    /// pod, and to distinguish it from other historical instances of the pod,
    /// but in tests or when Kubernetes introspection is set up incorrectly, a
    /// random UUID may be used instead. The consequence of using a random UUID
    /// is that health signals from the k8s Watch API cannot be correlated with
    /// the Slicelet incarnation, and the Assigner will rely exclusively on exit
    /// notice signals sent directly from the Slicelet.
    ///
    /// When determining whether a request is affinitized to the current
    /// Slicelet, the UUID is used only when assignment consistency is enabled.
    /// Otherwise, any assignment to the current `resource_address` is
    /// considered valid.
    pub fn resource_uuid(&self) -> &Uuid {
        &self.resource_uuid
    }

    /// Parses the given proto as a `Squid`, or returns an error if the proto is
    /// malformed.
    pub fn from_proto(proto: &SquidP) -> Result<Squid, Status> {
        // Parse the resource address.
        let resource_address_str: &str = proto
            .resource_address
            .as_ref()
            .map(|s| s.as_ref())
            .unwrap_or_default();
        let resource_address = ResourceAddress::new(resource_address_str)?;

        // Parse the creation time.
        let creation_time_millis: i64 = proto.creation_time_millis.unwrap_or_default();

        // Parse the resource UUID.
        let resource_uuid = Uuid::from_u64_pair(
            proto.resource_uuid_high.unwrap_or_default() as u64,
            proto.resource_uuid_low.unwrap_or_default() as u64,
        );

        Ok(Squid {
            resource_address,
            creation_time_millis,
            resource_uuid,
        })
    }

    /// Converts this SQUID to its proto representation.
    pub fn to_proto(&self) -> SquidP {
        let (resource_uuid_high, resource_uuid_low) = self.resource_uuid.as_u64_pair();
        SquidP {
            // Use the original string rather than `uri()`, which may render differently and so look
            // like a different resource to Scala (see `ResourceAddress::uri`).
            resource_address: Some(self.resource_address.as_str().to_string()),
            creation_time_millis: Some(self.creation_time_millis),
            resource_uuid_high: Some(resource_uuid_high as i64),
            resource_uuid_low: Some(resource_uuid_low as i64),
        }
    }
}

impl Ord for Squid {
    fn cmp(&self, other: &Self) -> Ordering {
        /// So that ordering is consistent with the reference Scala implementation of Squid, convert
        /// to signed high- and low- parts when comparing UUIDs (see java.util.UUID.compareTo).
        fn signed_uuid(uuid: &Uuid) -> (i64, i64) {
            let (high, low): (u64, u64) = uuid.as_u64_pair();
            (high.cast_signed(), low.cast_signed())
        }

        self.resource_address
            .cmp(&other.resource_address)
            .then_with(|| self.creation_time_millis.cmp(&other.creation_time_millis))
            .then_with(|| signed_uuid(&self.resource_uuid).cmp(&signed_uuid(&other.resource_uuid)))
    }
}

impl PartialOrd for Squid {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl Debug for Squid {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        write!(f, "[{}, ", self.resource_address())?;

        match system_time_from_unix_millis(self.creation_time_millis) {
            Some(time) => write!(f, "{:?}", PrettySystemTime(time))?,
            // This is not reachable on Linux for the reason documented on
            // `system_time_from_unix_millis`.
            None => write!(f, "?")?,
        }

        write!(f, ", {:?}]", self.resource_uuid())
    }
}
