//! Bazel driver for [`buffa_codegen`].
//!
//! Reads one or more [`FileDescriptorSet`] protos (produced by Bazel's
//! `proto_library` via `protoc`), feeds them to [`buffa_codegen::generate`],
//! and writes the resulting Rust source into a single Bazel-declared file.
//!
//! Bazel runs this binary once per `proto_library`, which writes one crate. That
//! target may list several `.proto` files but they all go into this crate, nested
//! by proto package.
//!
//! Replaces what `buffa-build` does in a Cargo `build.rs` workflow. With
//! Bazel the [`FileDescriptorSet`] is already available as a build output, so
//! the `protoc`-invocation half of `buffa-build` is unneeded.
//!
//! Each run also reads its dependencies' `package_info` manifests and writes
//! one for its own crate, so downstream crates reference these types instead
//! of regenerating them. See the [`package_info`] module.
use std::collections::{HashMap, HashSet};
use std::fmt::Write;
use std::path::PathBuf;

use anyhow::{bail, Context, Result};
use buffa::Message;
use buffa_codegen::generated::descriptor::{FileDescriptorProto, FileDescriptorSet};
use buffa_codegen::idents::escape_mod_ident;
use buffa_codegen::{generate, CodeGenConfig, GeneratedFile, GeneratedFileKind, ALLOW_LINTS};
use clap::Parser;

use crate::package_info::{package_info_for_generated_files, PackageInfo};

mod package_info;

/// Leading line Buffa writes on every generated file.
const GENERATED_FILE_HEADER: &str = "// @generated by buffa-codegen. DO NOT EDIT.\n";

/// One nesting level of indentation in the crate root, matching the 4-space indentation of
/// buffa's generated package bodies.
const INDENT: &str = "    ";

/// Command-line arguments.
#[derive(Parser)]
#[command(about = "Generate Rust source from FileDescriptorSet using buffa-codegen.")]
struct Args {
    /// Path where the generated crate root (`lib.rs`) is written.
    ///
    /// All generated modules are inlined into this one file.
    #[arg(long)]
    single_file: PathBuf,

    /// Name of the Rust crate being generated.
    ///
    /// Recorded in this crate's [`PackageInfo`] so downstream crates can reference its types.
    #[arg(long)]
    crate_name: String,

    /// Path where this crate's [`PackageInfo`] manifest is written.
    ///
    /// The manifest lists the proto files this crate owns and the Rust paths of their types.
    #[arg(long)]
    package_info_output: PathBuf,

    /// Path to a file listing dependency crates' [`PackageInfo`] manifest paths, one per line.
    ///
    /// Types from those crates are referenced instead of regenerated here.
    #[arg(long)]
    deps_info: PathBuf,

    /// Proto files this crate generates Rust source for.
    ///
    /// Names match [`FileDescriptorProto::name`]. A `proto_library` with
    /// several source files passes all of them.
    #[arg(long)]
    file_to_generate: Vec<String>,

    /// Proto files to skip, named as in [`FileDescriptorProto::name`].
    #[arg(long)]
    exclude: Vec<String>,

    /// Whether to emit [`buffa::text::TextFormat`] impls on generated message structs.
    #[arg(long)]
    text: bool,

    /// Paths to binary [`FileDescriptorSet`] files.
    ///
    /// Together the file descriptors cover this target's protos and their imports. Duplicates are
    /// merged by proto file name.
    #[arg(required = true)]
    fds: Vec<PathBuf>,
}

/// The proto files and type paths owned by this crate's dependency crates.
#[derive(Default)]
struct Dependencies {
    /// Files owned by dependency crates. This crate must not generate them.
    files: HashSet<String>,
    /// Exact proto FQN → absolute Rust path for every type declared in `files`, for
    /// [`CodeGenConfig::extern_paths`].
    extern_paths: HashMap<String, String>,
}

/// Checks that every file this crate generates and every dependency-owned file is in the
/// input descriptor sets.
///
/// A missing generated file is usually a Bazel path vs [`FileDescriptorProto::name`] slip. A
/// missing dependency file means `package_info` is stale relative to the FileDescriptorSets.
///
/// # Arguments
///
/// * `files_to_generate` - Proto files that the Rust crate will be generated for.
/// * `dependency_files` - Files listed in the dependency crates' manifests.
/// * `file_descriptors` - Every merged input file descriptor.
///
/// # Errors
///
/// Returns an error naming every generated or dependency file missing from the descriptor sets.
fn check_owned_files_exist_in_file_descriptors(
    files_to_generate: &[String],
    dependency_files: &HashSet<String>,
    file_descriptors: &[FileDescriptorProto],
) -> Result<()> {
    let input_files: HashSet<&str> = file_descriptors
        .iter()
        .filter_map(|file_descriptor: &FileDescriptorProto| file_descriptor.name.as_deref())
        .collect();
    let missing_generated: Vec<&str> = files_to_generate
        .iter()
        .map(String::as_str)
        .filter(|file: &&str| !input_files.contains(file))
        .collect();
    if !missing_generated.is_empty() {
        bail!("--file-to-generate {missing_generated:?} not found in the input descriptor sets");
    }
    let missing_dependency: Vec<&str> = dependency_files
        .iter()
        .map(String::as_str)
        .filter(|file: &&str| !input_files.contains(file))
        .collect();
    if !missing_dependency.is_empty() {
        bail!(
            "dependency manifests name {missing_dependency:?}, which are not in the input descriptor sets"
        );
    }
    Ok(())
}

/// Checks if any `--file-to-generate` file is already owned by a dependency crate.
///
/// Generating that file here would emit a second copy of those types.
///
/// # Arguments
///
/// * `files_to_generate` - Proto files that the Rust crate will be generated for.
/// * `dependency_files` - Files listed in the dependency crates' manifests.
///
/// # Errors
///
/// Returns an error naming every requested file already owned by a dependency crate.
fn check_generated_files_not_owned_by_dependencies(
    files_to_generate: &[String],
    dependency_files: &HashSet<String>,
) -> Result<()> {
    let owned_by_dependency: Vec<&str> = files_to_generate
        .iter()
        .map(String::as_str)
        .filter(|file: &&str| dependency_files.contains(*file))
        .collect();
    if !owned_by_dependency.is_empty() {
        bail!("{owned_by_dependency:?} are generated here but already owned by a dependency crate");
    }
    Ok(())
}

/// Checks if every file descriptor is generated here, owned by a dependency, or excluded.
///
/// An unclaimed file is invisible to Buffa. [`generate`] neither emits it nor adds its types
/// to [`CodeGenConfig::extern_paths`]. A later reference then fails as a missing module, or
/// a downstream crate regenerates the same types.
///
/// # Arguments
///
/// * `file_descriptors` - Every merged input file descriptor.
/// * `files_to_generate` - Proto files that the Rust crate will be generated for.
/// * `dependency_files` - Files listed in the dependency crates' manifests.
/// * `exclude` - Excluded proto file names.
///
/// # Errors
///
/// Returns an error naming every input file with no owner.
fn check_file_descriptors_have_owners(
    file_descriptors: &[FileDescriptorProto],
    files_to_generate: &[String],
    dependency_files: &HashSet<String>,
    exclude: &HashSet<String>,
) -> Result<()> {
    let input_files: HashSet<&str> = file_descriptors
        .iter()
        .filter_map(|file_descriptor: &FileDescriptorProto| file_descriptor.name.as_deref())
        .collect();
    let unowned: Vec<&str> = input_files
        .iter()
        .copied()
        .filter(|name: &&str| !files_to_generate.iter().any(|file: &String| file == name))
        .filter(|name: &&str| !dependency_files.contains(*name) && !exclude.contains(*name))
        .collect();
    if !unowned.is_empty() {
        bail!("no crate owns {unowned:?}");
    }
    Ok(())
}

/// Reads binary [`FileDescriptorSet`]s and flattens them into unique [`FileDescriptorProto`]s.
///
/// Each path is a Bazel `proto_library` descriptor set. Together they cover this crate's `.proto`
/// files and every proto they import.
///
/// # Arguments
///
/// * `fds` - The descriptor set paths from the command line, for this crate and its proto
///   dependencies.
///
/// # Returns
///
/// Unique [`FileDescriptorProto`]s in first-seen order.
///
/// # Errors
///
/// Returns an error if a file cannot be read or decoded, or if a descriptor has no proto file
/// name.
fn read_and_merge_fds(fds: &[PathBuf]) -> Result<Vec<FileDescriptorProto>> {
    let mut out: Vec<FileDescriptorProto> = Vec::new();
    let mut seen: HashSet<String> = HashSet::new();
    for path in fds {
        let data: Vec<u8> =
            std::fs::read(path).with_context(|| format!("read {}", path.display()))?;
        let fds: FileDescriptorSet = FileDescriptorSet::decode_from_slice(&data)
            .with_context(|| format!("decode FileDescriptorSet from {}", path.display()))?;
        for file in fds.file {
            let name: String = file.name.clone().with_context(|| {
                format!("FileDescriptorProto without name in {}", path.display())
            })?;
            if seen.insert(name) {
                out.push(file);
            }
        }
    }
    Ok(out)
}

/// Loads the proto files and type paths owned by this crate's dependencies from `--deps-info`.
///
/// `deps_info` is not a manifest itself. It is a newline-separated list of paths to the
/// dependency crates' manifests, written by `buffa.bzl` from their transitive `package_info`
/// files. Blank lines and `#` comments in that list are ignored.
///
/// # Arguments
///
/// * `deps_info` - Path to the list of dependency manifest paths.
///
/// # Returns
///
/// Every dependency file and type path, combined across all listed manifests.
///
/// # Errors
///
/// Returns an error if the list or a listed manifest cannot be read, if a manifest cannot be
/// parsed as a [`PackageInfo`], if two manifests claim the same proto file, or if two manifests
/// claim the same type FQN.
fn get_dependencies_from_deps_info(deps_info: &PathBuf) -> Result<Dependencies> {
    let content: String = std::fs::read_to_string(deps_info)
        .with_context(|| format!("read {}", deps_info.display()))?;
    let mut dependencies: Dependencies = Dependencies::default();
    // Two-level: this index lists manifests; each manifest records that crate's
    // owned files and type paths.
    for dep_path in content.lines() {
        let dep_path: &str = dep_path.trim();
        if dep_path.is_empty() || dep_path.starts_with('#') {
            continue;
        }
        let content: String = std::fs::read_to_string(dep_path)
            .with_context(|| format!("read dep package_info {dep_path}"))?;
        let package_info: PackageInfo = serde_json::from_str(&content)
            .with_context(|| format!("parse dep package_info {dep_path}"))?;
        for name in package_info.owned_file_names() {
            if !dependencies.files.insert(name.to_string()) {
                bail!("{name} is owned by more than one dependency crate, including {dep_path}");
            }
        }
        for (proto_fqn, rust_path) in package_info.extern_paths() {
            if dependencies
                .extern_paths
                .insert(proto_fqn.clone(), rust_path)
                .is_some()
            {
                bail!(
                    "{proto_fqn} is owned by more than one dependency crate, including {dep_path}"
                );
            }
        }
    }
    Ok(dependencies)
}

/// Builds the crate root by nesting each package body in one `pub mod` per package segment.
///
/// For bodies in packages `dicer` and `dicer.type`, the output is:
///
/// ```text
/// // @generated by buffa-codegen. DO NOT EDIT.
/// #![allow(<ALLOW_LINTS>)]
///
/// pub mod dicer {
///     use super::*;
///     <body of dicer>
///     pub mod r#type {
///         use super::*;
///         <body of dicer.type>
///     }
/// }
/// ```
///
/// Modules are emitted in sorted order, so the same inputs always produce the same bytes. Module
/// names go through [`escape_mod_ident`], the same escaping buffa uses for the paths that refer
/// to them.
///
/// # Arguments
///
/// * `package_mods` - Proto package name to package body. One entry per package.
///
/// # Returns
///
/// The crate root source, which is a generated-file header, crate-level `#![allow]` lints, then
/// the module tree.
fn emit_inlined_module_tree(package_mods: &HashMap<&str, &str>) -> String {
    // Sort is necessary because we want to generate all packages with similar parents in the same
    // `pub mod [package]` block (E0428 rejects duplicate definitions).
    let mut packages: Vec<(Vec<&str>, &str)> = package_mods
        .iter()
        .map(|(package, content): (&&str, &&str)| {
            let segments: Vec<&str> = package
                .split('.')
                .filter(|s: &&str| !s.is_empty())
                .collect();
            (segments, *content)
        })
        .collect();
    packages
        .sort_by(|(left, _): &(Vec<&str>, &str), (right, _): &(Vec<&str>, &str)| left.cmp(right));

    // Header: the `// @generated` line, then one crate-level `#![allow]` that covers every
    // module below it.
    let mut out: String = String::from(GENERATED_FILE_HEADER);
    let lints: String = ALLOW_LINTS.join(", ");
    let _ = writeln!(out, "#![allow({lints})]\n");

    // Stores the current package that we are working on (e.g., dicer.external.test would be
    // represented as ["dicer", "external", "test"]).
    let mut current_pkg: Vec<&str> = Vec::new();
    for (segments, content) in packages {
        // Length of common prefix between `current_pkg` and this package's path.
        //
        // `current_pkg = ["dicer", "external", "test"]`
        // `segments = ["dicer", "external", "src"]`
        // Our shared count would be two and this allows for dicer.external.src to be generated
        // inside of the existing `pub mod dicer { pub mod external {` block.
        let shared: usize = current_pkg
            .iter()
            .zip(&segments)
            .take_while(|(current_segment, segment): &(&&str, &&str)| current_segment == segment)
            .count();

        // Close previous modules below the common ancestor.
        //
        // Following our previous example `current_pkg.len()` = 3 and `shared = 2`, which
        // corresponds to closing out the `dicer.external.test` package. So the structure would
        // result in:
        // Generated: `pub mod dicer { pub mod external { pub mod test { ... }`
        while current_pkg.len() > shared {
            current_pkg.pop();
            let _ = writeln!(out, "{}}}", INDENT.repeat(current_pkg.len()));
        }

        // Open the rest of the package's path. Segments with no package of their own would
        // get an empty module (apart from the `use super::*;` line).
        //
        // `segment = ["dicer", "external", "src"]`
        // `shared = 2`
        // `segments[shared..] = ["src"]`
        // Generated: `pub mod dicer { pub mod external { pub mod test {} pub mod src {`
        for segment in &segments[shared..] {
            let indent: String = INDENT.repeat(current_pkg.len());
            let _ = writeln!(out, "{indent}pub mod {} {{", escape_mod_ident(segment));
            let _ = writeln!(out, "{indent}{INDENT}use super::*;");
            current_pkg.push(segment);
        }

        // Write the package body inside the current module.
        //
        // Generated: `pub mod dicer { pub mod external { pub mod test {} pub mod src { ...`
        let indent: String = INDENT.repeat(current_pkg.len());
        for line in content.lines() {
            if line.is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "{indent}{line}");
            }
        }
    }

    // Close the remaining modules.
    //
    // Generated: `pub mod dicer { pub mod external { pub mod test {} pub mod src { ... } } }`
    while current_pkg.pop().is_some() {
        let _ = writeln!(out, "{}}}", INDENT.repeat(current_pkg.len()));
    }
    out
}

/// Generates one Rust crate root and its [`PackageInfo`] manifest from descriptor sets.
///
/// Loads the dependency manifests, checks that every input file has an owner, generates the
/// files passed as `--file-to-generate`, writes the crate root to `--single-file`, then writes
/// this crate's manifest to `--package-info-output`.
///
/// # Errors
///
/// Returns an error if reading the inputs, the ownership check, code generation, or writing an
/// output fails. Invalid command-line arguments instead make clap print usage and exit the
/// process with status 2.
///
/// # Panics
///
/// Panics if [`buffa_codegen::generate`] panics.
fn main() -> Result<()> {
    let args = Args::parse();

    // File descriptors are decoded binary representations of this target's protos and the protos
    // they import. Buffa uses them to resolve schema types while generating Rust source.
    let file_descriptors: Vec<FileDescriptorProto> = read_and_merge_fds(&args.fds)?;

    // Dependencies are manifests of previously generated crates that this generation depends on.
    // They identify the proto files and Rust type paths provided by those crates.
    let dependencies: Dependencies = get_dependencies_from_deps_info(&args.deps_info)?;

    // Filter out files to generate if exclude argument explicitly references it. If all files
    // are filtered out then we error as each codegen run is expected to generate a crate.
    let exclude: HashSet<String> = args.exclude.into_iter().collect();
    let files_to_generate: Vec<String> = args
        .file_to_generate
        .into_iter()
        .filter(|file: &String| !exclude.contains(file))
        .collect();
    if files_to_generate.is_empty() {
        bail!("nothing to generate: no --file-to-generate remains after --exclude");
    }

    // Checks to ensure that generated crate is valid and all dependencies can be resolved.
    check_owned_files_exist_in_file_descriptors(
        &files_to_generate,
        &dependencies.files,
        &file_descriptors,
    )?;
    check_generated_files_not_owned_by_dependencies(&files_to_generate, &dependencies.files)?;
    check_file_descriptors_have_owners(
        &file_descriptors,
        &files_to_generate,
        &dependencies.files,
        &exclude,
    )?;

    let mut config = CodeGenConfig::default();
    config.generate_text = args.text;
    // Dependency types resolve through exact per-type `extern_paths`, so buffa references them in
    // their owning crates instead of generating them again here.
    config.extern_paths = dependencies.extern_paths.into_iter().collect();
    // Single-file output needs each package's generated content fully inlined.
    config.file_per_package = true;

    let generated: Vec<GeneratedFile> = generate(&file_descriptors, &files_to_generate, &config)
        .context("buffa_codegen::generate")?;

    // Write the crate root. With `file_per_package`, the `PackageMod` files already hold all of
    // the generated source, so the other generated files are skipped.
    let mut package_mods: HashMap<&str, &str> = HashMap::new();
    for generated_file in &generated {
        if generated_file.kind != GeneratedFileKind::PackageMod {
            continue;
        }
        let content: &str = match generated_file.content.strip_prefix(GENERATED_FILE_HEADER) {
            Some(rest) => rest.strip_prefix('\n').unwrap_or(rest),
            None => &generated_file.content,
        };
        if package_mods
            .insert(generated_file.package.as_str(), content)
            .is_some()
        {
            bail!("buffa emitted two PackageMod files for package {}", generated_file.package);
        }
    }
    let bundle: String = emit_inlined_module_tree(&package_mods);
    if let Some(parent) = args.single_file.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("create_dir_all {} (for --single-file)", parent.display()))?;
    }
    std::fs::write(&args.single_file, bundle)
        .with_context(|| format!("write {}", args.single_file.display()))?;

    // Write this crate's `PackageInfo`. Crates that depend on this one read it through their
    // `--deps-info` to learn which proto files this crate owns, so they do not generate them
    // again, and the Rust path of every type in those files, which becomes their exact per-type
    // `extern_paths`.
    let package_info: PackageInfo = package_info_for_generated_files(
        &args.crate_name,
        &file_descriptors,
        &files_to_generate,
        &config,
    )?;
    if let Some(parent) = args.package_info_output.parent() {
        std::fs::create_dir_all(parent).with_context(|| {
            format!("create_dir_all {} (for --package-info-output)", parent.display())
        })?;
    }
    let package_info_json: String =
        serde_json::to_string_pretty(&package_info).context("serialize package_info")?;
    std::fs::write(&args.package_info_output, package_info_json)
        .with_context(|| format!("write {}", args.package_info_output.display()))?;

    Ok(())
}
